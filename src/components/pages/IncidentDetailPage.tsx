import { MatchedRulesView, OutputInspectionView, ProvenanceHighlight, ProvenanceNote, StepsView } from '../IncidentExtras.tsx';
import React, { useState } from 'react';
import {
  ShieldAlert,
  ShieldCheck,
  Clock,
  ArrowLeft,
  Copy,
  Check,
  Ban,
  Share2,
  FileJson,
  KeyRound,
  ExternalLink,
  AlertTriangle,
  Send,
  Info,
  Database,
  Terminal,
  Download,
  Crosshair,
} from 'lucide-react';
import { Incident } from '../../../server/types.ts';

interface IncidentDetailPageProps {
  incident?: Incident;
  allIncidents: Incident[];
  onSelectIncident: (id: string) => void;
  onBack: () => void;
}

export const IncidentDetailPage: React.FC<IncidentDetailPageProps> = ({
  incident,
  allIncidents,
  onSelectIncident,
  onBack,
}) => {
  const [copied, setCopied] = useState(false);
  const [downloaded, setDownloaded] = useState(false);
  const [blocklistAdded, setBlocklistAdded] = useState(false);
  const [showIrModal, setShowIrModal] = useState(false);

  if (!incident) {
    return (
      <div className="cyber-card p-12 text-center text-[#8293aa] space-y-4 rounded border border-[#00e5ff]/20">
        <AlertTriangle className="w-8 h-8 text-[#00e5ff] mx-auto animate-pulse" />
        <h3 className="text-base font-bold font-heading text-white">No Incident Selected</h3>
        <p className="text-xs font-mono">Choose an incident from the Live Feed or select below:</p>
        <div className="flex flex-wrap justify-center gap-2">
          {allIncidents.slice(0, 5).map((inc) => (
            <button
              key={inc.id}
              onClick={() => onSelectIncident(inc.id)}
              className="px-3 py-1.5 rounded bg-[#090d18] border border-[#00e5ff]/30 hover:border-[#00e5ff] text-xs font-mono text-[#00e5ff] transition-all"
            >
              {inc.appName}: {inc.decision.ruleId} ({inc.id.substring(0, 10)})
            </button>
          ))}
        </div>
      </div>
    );
  }

  const handleCopyJson = () => {
    navigator.clipboard.writeText(JSON.stringify(incident, null, 2));
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownloadAuditReport = () => {
    const reportData = {
      reportMetadata: {
        reportType: 'SECURITY_INCIDENT_AUDIT_REPORT',
        generatedAt: new Date().toISOString(),
        gatewayVersion: '1.0.1',
        classification: 'RESTRICTED_SECURITY_AUDIT',
        complianceStandards: [
          'OWASP Top 10 for Large Language Model Applications (2025/2026)',
          'CERT-In Cybersecurity Directions (Section 70B)',
          'Digital Personal Data Protection Act (DPDP 2023)',
        ],
        disclaimer:
          'Audit report generated by LLM Firewall Action Gate & Credential Broker. Evaluates deterministic boundary decisions against active YAML policies. Contains synthetic test data.',
      },
      incidentSummary: {
        incidentId: incident.id,
        timestamp: incident.timestamp,
        appId: incident.appId || 'app_hr',
        appName: incident.appName || 'HR Assistant',
        scenarioId: incident.scenarioId,
        scenarioTitle: incident.scenarioTitle,
        firewallMode: incident.firewallMode,
        llmMode: incident.llmMode,
        riskLevel: incident.riskLevel,
        dataLeftPremises: incident.dataLeftPremises,
        latencyBreakdown: incident.latency,
      },
      actionGateDecision: {
        action: incident.decision.action,
        ruleId: incident.decision.ruleId,
        justification: incident.decision.reason,
        shadowWouldBlock: incident.decision.shadowWouldBlock,
        requiredApprovalId: incident.decision.requiredApprovalId || null,
        thesisEnforced: 'Reading untrusted content should never authorize a sensitive action.',
      },
      pipelineTimeline: [
        {
          step: 1,
          name: 'Inbound Content & Normalization',
          description: 'NFKC normalization, zero-width character stripping, bounded base64 decode inspection.',
          segmentsCount: incident.segments.length,
          segments: incident.segments.map((s) => ({
            id: s.id,
            role: s.role,
            trust: s.trust,
            labelSource: s.labelSource,
            contentExcerpt: s.content.length > 250 ? s.content.slice(0, 250) + '...' : s.content,
          })),
        },
        {
          step: 2,
          name: 'Multi-Signal Risk Detectors',
          description: 'Verhoeff Aadhaar, Luhn card, PAN regex, Canary token, Markdown exfil, Hinglish seeds.',
          findingsCount: incident.findings.length,
          findings: incident.findings.map((f) => ({
            id: f.id,
            detector: f.detector,
            category: f.category,
            severity: f.severity,
            confidence: f.confidence,
            spanOffset: [f.start, f.end],
            reason: f.reason,
            evidenceHash: f.evidenceHash,
          })),
        },
        {
          step: 3,
          name: 'Policy Engine Evaluation',
          description: 'Evaluation against deterministic YAML rules (R1-R6, Trifecta Guard).',
          matchedRule: incident.decision.ruleId,
          riskLevel: incident.riskLevel,
          shadowWouldBlock: incident.decision.shadowWouldBlock,
        },
        {
          step: 4,
          name: 'Action Gate Decision & Credential Minting',
          description: 'Deterministic credential minting boundary. Short-lived 60s Ed25519-signed token bound to the exact call vs a standing key (legacy-pattern simulation).',
          verdict: incident.decision.action,
          justification: incident.decision.reason,
          scopedTokenIssued: incident.decision.action === 'allow',
          standingKeysAllowed: false,
        },
        {
          step: 5,
          name: 'Protected Tool Server Outcome',
          description: 'Execution at tool boundary and outbox containment evaluation.',
          proposedTool: incident.toolCall?.tool || null,
          toolArgs: incident.toolCall?.args || null,
          executionResult: incident.toolResult || null,
          dataExfiltrated: incident.dataLeftPremises,
        },
        {
          step: 6,
          name: 'Counterfactual Analysis (Without Firewall)',
          description: 'Historical/counterfactual comparison if firewall was OFF (simulation of the legacy pattern, standing key).',
          withoutFirewallOutcome: incident.withoutFirewallOutcome || null,
        },
      ],
      findingsSummary: {
        totalFindings: incident.findings.length,
        criticalCount: incident.findings.filter((f) => f.severity === 'CRITICAL').length,
        highCount: incident.findings.filter((f) => f.severity === 'HIGH').length,
        mediumCount: incident.findings.filter((f) => f.severity === 'MEDIUM').length,
        lowCount: incident.findings.filter((f) => f.severity === 'LOW').length,
        categoriesDetected: Array.from(new Set(incident.findings.map((f) => f.category))),
      },
      noticesAndDisclaimers: [
        'Deterministic boundary for tool calls routed through the gate and verified by the tool server.',
        'Never claim 100% protection against adaptive adversarial attacks.',
        'Synthetic data only (fake Aadhaar/PAN, example.com addresses).',
        'Raw PII is never stored in finding records or logged in audit entries.',
      ],
    };

    const jsonString = JSON.stringify(reportData, null, 2);
    const blob = new Blob([jsonString], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `llm-firewall-incident-${incident.id}-audit-report.json`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);

    setDownloaded(true);
    setTimeout(() => setDownloaded(false), 2500);
  };

  const handleAddToBlocklist = () => {
    setBlocklistAdded(true);
    setTimeout(() => setBlocklistAdded(false), 3000);
  };

  // Helper to render segment text with highlighted suspicious spans using offset ranges
  const renderHighlightedContent = (content: string, segmentId: string) => {
    const relevantFindings = incident.findings.filter((f) => f.segmentId === segmentId);
    if (relevantFindings.length === 0) {
      return <span>{content}</span>;
    }

    // Sort findings by start offset
    const sorted = [...relevantFindings].sort((a, b) => a.start - b.start);
    const elements: React.ReactNode[] = [];
    let currentIdx = 0;

    sorted.forEach((f, idx) => {
      const safeStart = Math.max(0, Math.min(f.start, content.length));
      const safeEnd = Math.max(safeStart, Math.min(f.end, content.length));

      // Preceding normal text
      if (safeStart > currentIdx) {
        elements.push(
          <span key={`text_${currentIdx}`}>{content.slice(currentIdx, safeStart)}</span>
        );
      }

      // Highlighted suspicious text
      elements.push(
        <mark
          key={`highlight_${idx}`}
          title={`${f.category}: ${f.reason}`}
          className="bg-[#ff365d]/20 text-[#ff365d] border-b-2 border-[#ff365d] px-0.5 rounded-xs font-semibold cursor-help"
        >
          {content.slice(safeStart, safeEnd)}
        </mark>
      );

      currentIdx = safeEnd;
    });

    if (currentIdx < content.length) {
      elements.push(<span key={`text_end`}>{content.slice(currentIdx)}</span>);
    }

    return <>{elements}</>;
  };

  return (
    <div className="space-y-6">
      {/* Top Header & Context Actions */}
      <div className="cyber-card cyber-corner-tr rounded p-5">
        <div className="flex flex-col md:flex-row md:items-center justify-between gap-4 border-b border-[#00e5ff]/15 pb-4 mb-4">
          <div className="flex items-center gap-3">
            <button
              type="button"
              onClick={onBack}
              className="p-2 rounded bg-[#090d18] hover:bg-[#141f33] text-[#00e5ff] border border-[#00e5ff]/20 transition-colors"
            >
              <ArrowLeft className="w-4 h-4" />
            </button>
            <div>
              <div className="flex items-center gap-2">
                <h2 className="text-base font-bold font-heading text-white uppercase tracking-wide">
                  Incident Forensic Hero Timeline
                </h2>
                <span className="font-mono text-2xs text-[#00e5ff] bg-[#00e5ff]/10 border border-[#00e5ff]/30 px-2 py-0.5 rounded">
                  ID: {incident.id}
                </span>
                {incident.isSeeded && (
                  <span className="font-mono text-2xs text-[#8293aa] bg-[#141f33] px-1.5 py-0.5 rounded">
                    [SEEDED]
                  </span>
                )}
              </div>
              <p className="text-xs text-[#8293aa] font-mono mt-0.5">
                {incident.scenarioTitle} · App Target: <strong className="text-white">{incident.appName}</strong>
              </p>
            </div>
          </div>

          {/* Action Buttons */}
          <div className="flex flex-wrap items-center gap-2">
            {/* Download Audit JSON Report Button */}
            <button
              type="button"
              onClick={handleDownloadAuditReport}
              className="px-3 py-1.5 bg-gradient-to-r from-[#00e5ff] to-[#00a8ff] hover:from-[#33ecff] hover:to-[#33b8ff] text-[#080b12] font-black font-mono rounded text-xs shadow-[0_0_12px_rgba(0,229,255,0.4)] transition-all flex items-center gap-1.5 cursor-pointer"
              title="Generate and download full incident timeline, detector findings, and Action Gate decision justifications as a JSON report for security audits"
            >
              {downloaded ? (
                <Check className="w-3.5 h-3.5 text-[#080b12]" />
              ) : (
                <Download className="w-3.5 h-3.5 text-[#080b12]" />
              )}
              <span>{downloaded ? 'Report Downloaded!' : 'Download Audit JSON'}</span>
            </button>

            <button
              type="button"
              onClick={handleAddToBlocklist}
              className="px-3 py-1.5 bg-[#ff365d]/10 hover:bg-[#ff365d]/20 text-[#ff365d] border border-[#ff365d]/40 rounded text-xs font-mono font-semibold transition-colors flex items-center gap-1.5"
            >
              <Ban className="w-3.5 h-3.5 text-[#ff365d]" />
              {blocklistAdded ? 'Added to Indicator Blocklist!' : 'Add to Blocklist'}
            </button>

            <button
              type="button"
              onClick={() => setShowIrModal(true)}
              className="px-3 py-1.5 bg-[#090d18] hover:bg-[#141f33] text-slate-200 border border-[#00e5ff]/20 rounded text-xs font-mono font-semibold transition-colors flex items-center gap-1.5"
            >
              <ExternalLink className="w-3.5 h-3.5 text-[#00e5ff]" />
              Incident Response
            </button>

            <button
              type="button"
              onClick={handleCopyJson}
              className="px-3 py-1.5 bg-[#090d18] hover:bg-[#141f33] text-slate-200 border border-[#00e5ff]/20 rounded text-xs font-mono font-semibold transition-colors flex items-center gap-1.5"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-[#00e5ff]" /> : <Copy className="w-3.5 h-3.5 text-[#8293aa]" />}
              {copied ? 'Copied Evidence!' : 'Copy Evidence JSON'}
            </button>
          </div>
        </div>

        {/* Quick Incident Switcher Strip */}
        <div className="flex items-center gap-2 overflow-x-auto py-1 text-2xs font-mono">
          <span className="text-[#8293aa] shrink-0 uppercase tracking-wider">// Switch Incident:</span>
          {allIncidents.slice(0, 6).map((item) => (
            <button
              key={item.id}
              onClick={() => onSelectIncident(item.id)}
              className={`px-2.5 py-1 rounded shrink-0 transition-all border ${
                item.id === incident.id
                  ? 'bg-[#00e5ff]/10 border-[#00e5ff] text-[#00e5ff] font-bold shadow-[0_0_10px_rgba(0,229,255,0.2)]'
                  : 'bg-[#090d18] border-[#00e5ff]/15 text-[#8293aa] hover:text-white'
              }`}
            >
              {item.appName} ({item.decision.ruleId})
            </button>
          ))}
        </div>
      </div>

      {/* Two Column Layout: Hero Timeline vs Counterfactual Comparison */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
        {/* Left Column: Hero Vertical Timeline */}
        <div className="lg:col-span-7 cyber-card rounded p-5 space-y-6">
          <h3 className="text-sm font-bold font-heading text-white uppercase tracking-wider flex items-center gap-2 border-b border-[#00e5ff]/15 pb-3">
            <Terminal className="w-4 h-4 text-[#00e5ff]" />
            Pipeline Forensic Execution Timeline
          </h3>

          <div className="relative border-l-2 border-[#00e5ff]/30 ml-4 space-y-8 pl-6">
            {/* Step 1: Input & Ingestion */}
            <div className="relative">
              <span className="absolute -left-9 top-0.5 w-6 h-6 rounded-full bg-[#050810] border-2 border-[#00e5ff] flex items-center justify-center text-[#00e5ff] font-bold font-mono text-2xs shadow-[0_0_8px_#00e5ff]">
                1
              </span>
              <div>
                <span className="text-xs font-bold font-mono uppercase tracking-wide text-[#00e5ff]">
                  Step 1: Inbound Content &amp; Input Normalization
                </span>
                <p className="text-2xs text-[#8293aa] font-mono mt-0.5">
                  NFKC normalized, zero-width characters stripped, bounded base64 inspected.
                </p>
                <div className="mt-2 space-y-2">
                  {incident.segments.map((seg) => (
                    <div key={seg.id} className="p-3 bg-[#090d18] rounded border border-[#00e5ff]/15 text-xs">
                      <div className="flex items-center justify-between text-2xs mb-1.5 font-mono">
                        <span className="text-slate-300 font-semibold uppercase">Role: {seg.role}</span>
                        <div className="flex items-center gap-2">
                          <span
                            className={`px-1.5 py-0.5 rounded font-bold ${
                              seg.trust === 'SYSTEM' || seg.trust === 'USER'
                                ? 'bg-[#00e5ff]/10 text-[#00e5ff] border border-[#00e5ff]/30'
                                : 'bg-[#ff365d]/10 text-[#ff365d] border border-[#ff365d]/30'
                            }`}
                          >
                            [{seg.trust}]
                          </span>
                          <span className="text-[#8293aa]">Label source: {seg.labelSource}</span>
                        </div>
                      </div>
                      <pre className="text-2xs font-mono text-slate-200 whitespace-pre-wrap max-h-36 overflow-y-auto bg-[#050810] p-2.5 rounded border border-[#00e5ff]/10 scanlines-overlay">
                        {renderHighlightedContent(seg.content, seg.id)}
                      </pre>
                      {incident.argProvenance && <ProvenanceHighlight segment={seg} matches={incident.argProvenance.matches} />}
                    </div>
                  ))}
                </div>
                <ProvenanceNote provenance={incident.argProvenance} />
                <StepsView steps={incident.steps} />
                <OutputInspectionView items={incident.outputInspections} />
                {incident.honestyNote && <div className="mt-2 p-2 bg-[#ffb020]/10 border border-[#ffb020]/30 rounded text-3xs text-[#ffd27a] font-mono">{incident.honestyNote}</div>}
              </div>
            </div>

            {/* Step 2: Risk Signals & Suspicious Span Detections */}
            <div className="relative">
              <span className="absolute -left-9 top-0.5 w-6 h-6 rounded-full bg-[#050810] border-2 border-[#ff365d] flex items-center justify-center text-[#ff365d] font-bold font-mono text-2xs shadow-[0_0_8px_#ff365d]">
                2
              </span>
              <div>
                <div className="flex items-center justify-between">
                  <span className="text-xs font-bold font-mono uppercase tracking-wide text-[#ff365d]">
                    Step 2: Risk Signals &amp; Evidence Hashes
                  </span>
                  <span className="text-2xs font-mono text-[#8293aa]">
                    {incident.findings.length} Finding(s) detected
                  </span>
                </div>
                <div className="mt-2 space-y-2">
                  {incident.findings.map((fnd) => (
                    <div key={fnd.id} className="p-3 bg-[#150a10] rounded border border-[#ff365d]/30 text-xs">
                      <div className="flex items-center justify-between text-2xs mb-1 font-mono">
                        <span className="font-bold text-[#ff365d]">{fnd.category}</span>
                        <span className="font-bold text-[#ff365d] bg-[#ff365d]/10 border border-[#ff365d]/40 px-1.5 py-0.5 rounded">
                          {fnd.severity} ({Math.round(fnd.confidence * 100)}%)
                        </span>
                      </div>
                      <p className="text-2xs text-slate-300 mb-1">{fnd.reason}</p>
                      <div className="text-2xs font-mono text-[#8293aa] truncate">
                        Span Offset: [{fnd.start}..{fnd.end}] · Evidence Hash: {fnd.evidenceHash}
                      </div>
                    </div>
                  ))}
                </div>
              </div>
            </div>

            {/* Step 3: Policy Engine Evaluation */}
            <div className="relative">
              <span className="absolute -left-9 top-0.5 w-6 h-6 rounded-full bg-[#050810] border-2 border-[#818cf8] flex items-center justify-center text-[#818cf8] font-bold font-mono text-2xs shadow-[0_0_8px_#818cf8]">
                3
              </span>
              <div>
                <span className="text-xs font-bold font-mono uppercase tracking-wide text-[#818cf8]">
                  Step 3: Policy Rule Evaluation
                </span>
                <div className="mt-2 p-3 bg-[#090d18] rounded border border-[#00e5ff]/15 text-xs space-y-1 font-mono">
                  <div className="flex items-center justify-between text-slate-300">
                    <span>Matched Security Rule:</span>
                    <span className="text-[#00e5ff] font-bold">{incident.decision.ruleId}</span>
                  </div>
                  <div className="flex items-center justify-between text-[#8293aa] text-2xs">
                    <span>Calculated Session Risk Level:</span>
                    <span className="text-[#ff365d] font-bold">{incident.riskLevel}</span>
                  </div>
                  <div className="flex items-center justify-between text-[#8293aa] text-2xs">
                    <span>Shadow Mode Simulation:</span>
                    <span>{incident.decision.shadowWouldBlock ? 'Would have Blocked' : 'Would Allow'}</span>
                  </div>
                  <MatchedRulesView decision={incident.decision} />
                </div>
              </div>
            </div>

            {/* Step 4: Action Gate Decision & Token Boundary */}
            <div className="relative">
              <span className="absolute -left-9 top-0.5 w-6 h-6 rounded-full bg-[#050810] border-2 border-[#00e5ff] flex items-center justify-center text-[#00e5ff] font-bold font-mono text-2xs shadow-[0_0_8px_#00e5ff]">
                4
              </span>
              <div>
                <span className="text-xs font-bold font-mono uppercase tracking-wide text-[#00e5ff]">
                  Step 4: Action Gate Boundary &amp; Credential Minting
                </span>
                <div
                  className={`mt-2 p-3 rounded border text-xs font-mono ${
                    incident.decision.action === 'allow'
                      ? 'bg-[#00f5a0]/10 border-[#00f5a0]/40 text-[#00f5a0]'
                      : incident.decision.action === 'approve'
                      ? 'bg-[#ffb020]/10 border-[#ffb020]/40 text-[#ffb020]'
                      : 'bg-[#ff365d]/10 border-[#ff365d]/40 text-[#ff365d]'
                  }`}
                >
                  <div className="flex items-center gap-2 font-bold uppercase text-2xs mb-1">
                    {incident.decision.action === 'allow' ? (
                      <ShieldCheck className="w-4 h-4 text-[#00f5a0]" />
                    ) : incident.decision.action === 'approve' ? (
                      <Clock className="w-4 h-4 text-[#ffb020]" />
                    ) : (
                      <ShieldAlert className="w-4 h-4 text-[#ff365d]" />
                    )}
                    <span>Boundary Verdict: {incident.decision.action}</span>
                  </div>
                  <p className="text-2xs">{incident.decision.reason}</p>
                </div>
              </div>
            </div>

            {/* Step 5: Final Tool Server Outcome */}
            <div className="relative">
              <span className="absolute -left-9 top-0.5 w-6 h-6 rounded-full bg-[#050810] border-2 border-[#00f5a0] flex items-center justify-center text-[#00f5a0] font-bold font-mono text-2xs shadow-[0_0_8px_#00f5a0]">
                5
              </span>
              <div>
                <span className="text-xs font-bold font-mono uppercase tracking-wide text-[#00f5a0]">
                  Step 5: Protected Tool Server Outcome
                </span>
                <div className="mt-2 p-3 bg-[#090d18] rounded border border-[#00e5ff]/15 text-xs space-y-1 font-mono">
                  {incident.toolCall ? (
                    <>
                      <div className="text-slate-300 font-bold">Tool: {incident.toolCall.tool}()</div>
                      <div className="text-2xs text-[#8293aa]">
                        Credential Info: {incident.toolResult?.credentialInfo || 'None'}
                      </div>
                      <div className="text-2xs text-[#8293aa]">
                        Result: {incident.toolResult?.error || JSON.stringify(incident.toolResult?.data)}
                      </div>
                      <div className="text-2xs text-[#00f5a0] font-bold pt-1 border-t border-[#00e5ff]/10">
                        {incident.dataLeftPremises ? '⚠️ DATA TRANSMITTED' : '✓ ZERO DATA EXFILTRATION'}
                      </div>
                    </>
                  ) : (
                    <div className="text-[#8293aa] text-2xs">No tool invoked by agent response.</div>
                  )}
                </div>
              </div>
            </div>
          </div>
        </div>

        {/* Right Column: "Why Blocked" Box & "Without Firewall" Counterfactual */}
        <div className="lg:col-span-5 space-y-6">
          {/* Plain Language "Why Blocked" Box */}
          <div className="cyber-card p-5 rounded space-y-3">
            <h4 className="text-xs font-bold font-heading text-white uppercase tracking-wider flex items-center gap-2">
              <Info className="w-4 h-4 text-[#00e5ff]" />
              Plain Language Explanation: Why Blocked
            </h4>

            <div className="p-3.5 bg-[#090d18] rounded border border-[#00e5ff]/15 text-xs text-slate-300 leading-relaxed font-sans">
              {incident.decision.action === 'deny' ? (
                <>
                  The agent read an untrusted document containing hidden directives and attempted to invoke sensitive tool{' '}
                  <code className="text-[#00e5ff] font-mono font-bold">
                    {incident.toolCall?.tool || 'send_email'}
                  </code>
                  . Under policy rule{' '}
                  <strong className="text-white">{incident.decision.ruleId}</strong>, untrusted sessions cannot authorize external or financial actions. The Action Gate refused to mint a broker token, preventing the tool server from executing.
                </>
              ) : incident.decision.action === 'approve' ? (
                <>
                  The requested operation involves external communication or exceeds financial thresholds. The Action Gate held the call in the Human Approval Queue with a 60-second auto-expiration window.
                </>
              ) : (
                <>
                  The tool invocation was deemed benign under active policy rules and was granted a single-use 60-second micro-token bound to the exact arguments.
                </>
              )}
            </div>
          </div>

          {/* Side-by-Side Panel: Without Firewall — What Would Have Happened */}
          <div className="cyber-card cyber-card-crimson p-5 rounded space-y-3">
            <div className="flex items-center justify-between border-b border-[#ff365d]/20 pb-2">
              <h4 className="text-xs font-bold font-heading text-[#ff365d] uppercase tracking-wider flex items-center gap-2">
                <AlertTriangle className="w-4 h-4 text-[#ff365d]" />
                Without Firewall: What Would Have Happened
              </h4>
              <span className="text-2xs font-mono text-[#ff365d] font-bold bg-[#ff365d]/10 px-2 py-0.5 rounded border border-[#ff365d]/30">
                OFF-MODE CONTRAST
              </span>
            </div>

            {incident.withoutFirewallOutcome ? (
              <div className="space-y-3 text-xs font-mono">
                <div className="p-3 bg-[#050810] border border-[#ff365d]/30 rounded space-y-2">
                  <div className="text-slate-300 font-semibold">
                    Attacker Action Obeyed:
                  </div>
                  <pre className="text-2xs text-[#ff365d] bg-black/60 p-2 rounded whitespace-pre-wrap">
                    {incident.withoutFirewallOutcome.tool}({JSON.stringify(incident.withoutFirewallOutcome.args, null, 2)})
                  </pre>
                  <div className="text-2xs text-slate-300">
                    <strong className="text-[#ff365d]">Impact: </strong>
                    {incident.withoutFirewallOutcome.impact}
                  </div>
                  {incident.withoutFirewallOutcome.financialLoss && (
                    <div className="text-2xs text-[#ffb020] font-bold">
                      Potential Loss: {incident.withoutFirewallOutcome.financialLoss}
                    </div>
                  )}
                </div>

                <div className="text-2xs text-[#8293aa] leading-relaxed font-sans">
                  In legacy agent setups, the agent holds a standing key (Simulation of the legacy pattern). An adversary hijacking the prompt can call tools without restrictions, argument constraints, or approval gates.
                </div>
              </div>
            ) : (
              <p className="text-xs text-[#8293aa] font-mono">
                In off-mode, the agent executes all tool calls using a standing key without argument constraints (Simulation of the legacy pattern).
              </p>
            )}
          </div>
        </div>
      </div>

      {/* Incident Response Playbook Modal */}
      {showIrModal && (
        <div className="fixed inset-0 z-50 bg-black/85 flex items-center justify-center p-4">
          <div className="cyber-card max-w-lg w-full p-6 space-y-4 text-xs rounded border border-[#00e5ff]/40 shadow-2xl">
            <div className="flex items-center justify-between border-b border-[#00e5ff]/20 pb-3">
              <h3 className="text-sm font-bold font-heading text-white flex items-center gap-2">
                <ShieldAlert className="w-4 h-4 text-[#ff365d]" />
                Incident Response Remediation Playbook
              </h3>
              <button
                type="button"
                onClick={() => setShowIrModal(false)}
                className="text-[#8293aa] hover:text-white"
              >
                ✕
              </button>
            </div>

            <div className="space-y-3 text-slate-300 font-mono">
              <p>
                <strong>Incident ID:</strong> <code className="text-[#00e5ff]">{incident.id}</code>
              </p>
              <p>
                <strong>Rule Enforced:</strong> <code className="text-[#ff365d]">{incident.decision.ruleId}</code>
              </p>
              <div className="p-3 bg-[#050810] rounded border border-[#00e5ff]/20 space-y-1.5 text-2xs">
                <div>[Step 1] Quarantine source document segment ID {incident.segments[1]?.id || 'doc'}.</div>
                <div>[Step 2] Add recipient address to permanent firewall domain blocklist.</div>
                <div>[Step 3] Confirm Protected Tool Server Outbox: Zero bytes exfiltrated.</div>
                <div>[Step 4] Cryptographic audit chain verified at seq #{incident.latency.totalMs}.</div>
              </div>
            </div>

            <div className="flex justify-end pt-2">
              <button
                type="button"
                onClick={() => setShowIrModal(false)}
                className="px-4 py-2 bg-[#00e5ff] hover:bg-[#33ecff] text-[#080b12] font-black font-mono rounded text-xs"
              >
                Close Playbook
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
